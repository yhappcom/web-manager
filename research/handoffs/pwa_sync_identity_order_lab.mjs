import assert from 'node:assert/strict';
const passed=[];
const check=(id,fn)=>{fn();passed.push(id)};
const u8=(a,b)=>Math.sign(Buffer.compare(Buffer.from(a,'utf8'),Buffer.from(b,'utf8')));
const u16=(a,b)=>Math.sign(a<b?-1:a>b?1:0);
const order=(a,b)=>a.t===b.t?u8(a.id,b.id):(a.t>b.t?1:-1);
const winner=(a,b)=>order(a,b)>=0?a:b;
const admit=(seen,op)=>{const prior=seen.get(op.id);if(prior&&prior!==op.digest)return 'COLLISION';if(prior)return 'RETRY';seen.set(op.id,op.digest);return 'NEW'};
const a={id:'a',t:100n,digest:'A',kind:'UPDATE'};
const b={id:'b',t:101n,digest:'B',kind:'UPDATE'};
check('U01 ASCII ordering',()=>assert.equal(u8('a0','af'),u16('a0','af')));
check('U02 UTF8 BMP/nonBMP order',()=>assert.equal(u8('\uE000','\u{10000}'),-1));
check('U03 UTF16 opposite order',()=>assert.equal(u16('\uE000','\u{10000}'),1));
check('U04 winner mismatch with default JS sort',()=>{const x={id:'\uE000',t:10n},y={id:'\u{10000}',t:10n};assert.equal(winner(x,y).id,y.id);assert.equal([x.id,y.id].sort().at(-1),x.id)});
check('U05 canonical-equivalent strings differ as IDs',()=>{const x='\u00E9',y='e\u0301';assert.notEqual(x,y);assert.equal(x.normalize('NFC'),y.normalize('NFC'));assert.notEqual(u8(x,y),0)});
check('U06 lone surrogate replaced by UTF8 encoder',()=>assert.equal(Buffer.from('\uD800','utf8').toString('hex'),Buffer.from('\uFFFD','utf8').toString('hex')));
check('U07 time dominates ID',()=>assert.equal(winner(a,b).id,'b'));
check('U08 delivery inversion',()=>assert.equal(winner(a,b).id,winner(b,a).id));
check('U09 tie uses ID',()=>assert.equal(winner({id:'a',t:10n},{id:'b',t:10n}).id,'b'));
check('U10 same-ID same-digest retry',()=>{const s=new Map();assert.equal(admit(s,a),'NEW');assert.equal(admit(s,a),'RETRY')});
check('U11 same-ID changed-digest collision',()=>{const s=new Map();admit(s,a);assert.equal(admit(s,{...a,digest:'X'}),'COLLISION')});
check('U12 unsafe distant microseconds',()=>{const x=253402300799999998n,y=x+1n;assert.ok(x<y);assert.equal(Number(x),Number(y))});
check('U13 Date.parse loses microseconds',()=>assert.equal(Date.parse('2026-10-27T10:00:00.123001Z'),Date.parse('2026-10-27T10:00:00.123002Z')));
check('U14 future tombstone wins',()=>assert.equal(winner({id:'z',t:200n,kind:'DELETE'},{id:'y',t:199n,kind:'UPDATE'}).kind,'DELETE'));
check('U15 same flight key not same record ID',()=>{const x={record:'r1',flight:'AB123'},y={record:'r2',flight:'AB123'};assert.equal(x.flight,y.flight);assert.notEqual(x.record,y.record)});
check('U16 sector mismatch despite same key',()=>{const x={date:'2026-10-27',flight:'AB123',to:'NRT'},y={...x,to:'KIX'};assert.equal(x.flight,y.flight);assert.notEqual(x.to,y.to)});
check('U17 normalization changes identity',()=>assert.notEqual('e\u0301','\u00e9'));
